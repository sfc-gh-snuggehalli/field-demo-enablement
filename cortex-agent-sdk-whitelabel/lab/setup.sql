-- =====================================================================
-- ACME Assist — Snowflake objects for the Cortex Agent SDK app demo
-- Creates: database, warehouse, demo role, seed tables, semantic view,
--          ACME_ASSIST_AGENT (Analyst + client-side browser tools are
--          supplied per request by the app) and ACME_POWER_AGENT
--          (code_toolset_all, always_ask).
-- Run order: setup.sql -> seed_data.sql -> section 4+ of this file (below
--            the "AFTER SEED" marker), or simply run the whole file after
--            seed_data.sql has been run once (it is idempotent).
-- Role: SYSADMIN for objects; ACCOUNTADMIN only for the grants in section 6.
-- =====================================================================

USE ROLE SYSADMIN;

-- 1. Database, schemas, warehouse --------------------------------------
CREATE DATABASE IF NOT EXISTS ACME_ASSIST_DEMO;
CREATE SCHEMA IF NOT EXISTS ACME_ASSIST_DEMO.DATA;
CREATE SCHEMA IF NOT EXISTS ACME_ASSIST_DEMO.APP;   -- conversation history + App Runtime target

CREATE WAREHOUSE IF NOT EXISTS ACME_ASSIST_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

USE SCHEMA ACME_ASSIST_DEMO.DATA;
USE WAREHOUSE ACME_ASSIST_WH;

-- 2. Tables (shape matches app/src/apps/storeops/data/*.json) ----------
CREATE TABLE IF NOT EXISTS REGIONS (
  region_id STRING PRIMARY KEY, region_name STRING, manager STRING, store_count NUMBER,
  currency STRING, weekly_sales_target NUMBER(14,2), stockout_threshold_pct NUMBER(5,2));
CREATE TABLE IF NOT EXISTS PRODUCTS (
  sku STRING PRIMARY KEY, name STRING, category STRING, subcategory STRING, brand STRING,
  unit_cost NUMBER(10,2), list_price NUMBER(10,2));
CREATE TABLE IF NOT EXISTS INVENTORY (
  region_id STRING, sku STRING, on_hand NUMBER, on_order NUMBER, daily_run_rate NUMBER(8,1),
  weeks_of_cover NUMBER(8,1), inventory_value NUMBER(14,2), stockout_flag BOOLEAN);
CREATE TABLE IF NOT EXISTS DAILY_SALES (
  sales_date DATE, region_id STRING, sku STRING, units NUMBER, revenue NUMBER(14,2));
CREATE TABLE IF NOT EXISTS ORDERS (
  order_id STRING PRIMARY KEY, region_id STRING, sku STRING, channel STRING, qty NUMBER,
  unit_price NUMBER(10,2), order_date DATE, promised_date DATE, carrier STRING, status STRING);
CREATE TABLE IF NOT EXISTS FULFILLMENT_EXCEPTIONS (
  exception_id STRING PRIMARY KEY, order_id STRING, reason STRING, age_hours NUMBER,
  assignee STRING, status STRING);
CREATE TABLE IF NOT EXISTS REGION_RISK (
  region_id STRING PRIMARY KEY, stockout_rate_pct NUMBER(6,1), stockout_threshold_pct NUMBER(5,2),
  stockout_breach BOOLEAN, gross_margin_pct NUMBER(6,1), sales_7d NUMBER(16,2),
  sales_vs_target_pct NUMBER(7,1), sales_breach BOOLEAN);

