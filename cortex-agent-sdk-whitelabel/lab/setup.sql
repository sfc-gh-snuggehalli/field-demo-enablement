-- 4. Semantic view ------------------------------------------------------
CREATE OR REPLACE SEMANTIC VIEW ACME_ASSIST_DEMO.DATA.ACME_SEMANTIC_VIEW
  TABLES (
    regions AS ACME_ASSIST_DEMO.DATA.REGIONS PRIMARY KEY (region_id)
      WITH SYNONYMS = ('region', 'store cluster') COMMENT = 'ACME Retail regions (store clusters).',
    products AS ACME_ASSIST_DEMO.DATA.PRODUCTS PRIMARY KEY (sku)
      WITH SYNONYMS = ('product', 'item', 'SKU') COMMENT = 'Product catalog.',
    inventory AS ACME_ASSIST_DEMO.DATA.INVENTORY
      COMMENT = 'Current store inventory per region and SKU.',
    sales AS ACME_ASSIST_DEMO.DATA.DAILY_SALES
      COMMENT = 'Daily units and revenue per region and SKU, last 30 days.',
    orders AS ACME_ASSIST_DEMO.DATA.ORDERS PRIMARY KEY (order_id)
      COMMENT = 'Customer orders and fulfillment status.',
    exceptions AS ACME_ASSIST_DEMO.DATA.FULFILLMENT_EXCEPTIONS PRIMARY KEY (exception_id)
      WITH SYNONYMS = ('fulfillment exceptions', 'breaks') COMMENT = 'Open fulfillment exceptions.',
    risk AS ACME_ASSIST_DEMO.DATA.REGION_RISK PRIMARY KEY (region_id)
      COMMENT = 'Per-region stockout, margin and sales-vs-target risk.'
  )
  RELATIONSHIPS (
    inventory_region AS inventory (region_id) REFERENCES regions,
    inventory_product AS inventory (sku) REFERENCES products,
    sales_region AS sales (region_id) REFERENCES regions,
    sales_product AS sales (sku) REFERENCES products,
    orders_region AS orders (region_id) REFERENCES regions,
    orders_product AS orders (sku) REFERENCES products,
    exceptions_order AS exceptions (order_id) REFERENCES orders,
    risk_region AS risk (region_id) REFERENCES regions
  )
  FACTS (
    inventory.on_hand_units AS on_hand,
    inventory.inventory_value_usd AS inventory_value,
    inventory.is_stockout AS IFF(stockout_flag, 1, 0),
    orders.is_failed AS IFF(status = 'FAILED', 1, 0),
    sales.sales_units AS units,
    sales.sales_revenue AS revenue,
    orders.order_value AS qty * unit_price,
    exceptions.exception_age_hours AS age_hours
  )
  DIMENSIONS (
    regions.region_id AS region_id,
    regions.region_name AS region_name WITH SYNONYMS = ('region name') COMMENT = 'West, Central, South, Northeast.',
    regions.manager AS manager,
    regions.stockout_threshold_pct AS stockout_threshold_pct COMMENT = 'Max allowed % of SKUs out of stock.',
    products.sku AS sku,
    products.product_name AS name,
    products.category AS category COMMENT = 'Apparel, Footwear, Home, Electronics, Outdoor.',
    products.subcategory AS subcategory,
    inventory.stockout_flag AS stockout_flag COMMENT = 'TRUE when on hand is zero or cover < 0.3 weeks.',
    inventory.weeks_of_cover AS weeks_of_cover,
    sales.sales_date AS sales_date,
    orders.order_id AS order_id,
    orders.channel AS channel COMMENT = 'STORE, ONLINE or BOPIS.',
    orders.order_status AS status COMMENT = 'NEW, PICKED, SHIPPED, FAILED or BACKORDERED.',
    orders.order_date AS order_date,
    orders.carrier AS carrier,
    exceptions.exception_id AS exception_id,
    exceptions.exception_reason AS reason COMMENT = 'Address mismatch, Qty short, Late pick, Carrier delay.',
    exceptions.assignee AS assignee,
    exceptions.exception_status AS status,
    risk.stockout_rate_pct AS stockout_rate_pct,
    risk.stockout_breach AS stockout_breach COMMENT = 'TRUE when stockout rate exceeds the region threshold.',
    risk.gross_margin_pct AS gross_margin_pct,
    risk.sales_vs_target_pct AS sales_vs_target_pct
  )
  METRICS (
    inventory.total_on_hand AS SUM(inventory.on_hand_units),
    inventory.total_inventory_value AS SUM(inventory.inventory_value_usd),
    inventory.sku_count AS COUNT(inventory.sku),
    inventory.stockout_sku_count AS SUM(inventory.is_stockout),
    sales.total_units AS SUM(sales.sales_units),
    sales.total_revenue AS SUM(sales.sales_revenue),
    orders.order_count AS COUNT(orders.order_id),
    orders.failed_order_count AS SUM(orders.is_failed),
    orders.total_order_value AS SUM(orders.order_value),
    exceptions.exception_count AS COUNT(exceptions.exception_id),
    exceptions.avg_exception_age_hours AS AVG(exceptions.exception_age_hours)
  )
  COMMENT = 'ACME Retail store operations: inventory, sales, orders, fulfillment exceptions and regional risk.';

-- 5. Agents -------------------------------------------------------------
-- Browser tools (browser_open_app, browser_navigate, browser_click, ...) are
-- NOT declared here: the app sends them as client-side `generic` tools on each
-- request, so the React client executes them against the sidebar.
CREATE OR REPLACE AGENT ACME_ASSIST_DEMO.DATA.ACME_ASSIST_AGENT
  COMMENT = 'ACME Assist: retail store-operations assistant (Analyst + client-side browser tools).'
  FROM SPECIFICATION $$
models:
  orchestration: claude-sonnet-4-5
instructions:
  orchestration: |
    You are ACME Assist, the store-operations assistant for ACME Retail regional, store and
    fulfillment teams. Data covers 4 regions (West, Central, South, Northeast), ~25 SKUs,
    current inventory, 30 days of sales, recent orders, fulfillment exceptions and regional risk.
    - Use acme_analyst for any number, count, ranking, trend or comparison.
    - When the user asks to SEE, OPEN, SHOW, FILTER or ACT in an app, use the browser_* tools
      if they are available in this request (ACME Store Ops at /apps/storeops).
    - Always call browser_get_page before browser_click, browser_fill or browser_select, and
      target elements by their data-testid.
    - For "which region is breaching" questions: answer from acme_analyst, then open
      /apps/storeops/risk and browser_highlight the breach row.
    - "me" / "assign to me" refers to the user named in the user-context section, if provided.
  response: |
    Lead with the direct answer in one or two sentences, then supporting numbers. Use tables for
    more than three rows. Name the region and SKU explicitly. Keep it concise and operational.
  sample_questions:
    - question: "Which region is breaching its stockout threshold?"
    - question: "Show me today's failed orders for the West region"
    - question: "Assign the oldest Address mismatch exception to me"
    - question: "What were total sales by category over the last 7 days?"
tools:
  - tool_spec:
      type: cortex_analyst_text_to_sql
      name: acme_analyst
      description: |
        Text-to-SQL over ACME Retail store operations (ACME_SEMANTIC_VIEW): regions, products,
        inventory (on hand, weeks of cover, stockout flag), daily sales (units, revenue, 30 days),
        orders (channel, status, carrier), fulfillment exceptions (reason, age, assignee) and
        regional risk (stockout rate vs threshold, margin, sales vs target). Use for any numeric
        or tabular question. Do not use for navigating apps.
  - tool_spec:
      type: data_to_chart
      name: data_to_chart
      description: Generate a chart from data returned by acme_analyst when a visual helps.
tool_resources:
  acme_analyst:
    semantic_view: ACME_ASSIST_DEMO.DATA.ACME_SEMANTIC_VIEW
    execution_environment:
      type: warehouse
      warehouse: ACME_ASSIST_WH
$$;

-- Power Mode agent: full Cortex Code sandbox toolset (Preview). Keep always_ask.
CREATE OR REPLACE AGENT ACME_ASSIST_DEMO.DATA.ACME_POWER_AGENT
  COMMENT = 'ACME Assist Power Mode: code_toolset_all sandbox + Analyst (Preview).'
  FROM SPECIFICATION $$
models:
  orchestration: claude-sonnet-4-5
instructions:
  orchestration: |
    You are ACME Assist in Power Mode. Query data ONLY through acme_analyst (the sandbox has no
    data access), then use the coding sandbox to build files: CSV, charts (SVG or self-contained
    HTML), and short reports. Write every deliverable with the write tool under ./output/ in the
    workspace and say their file names in the answer. Browser tools, if provided, reach the user's sidebar app.
  response: |
    Summarize what you produced, list output files, and give the key numbers.
tools:
  - tool_spec:
      type: code_toolset_all
      name: coding_agent
  - tool_spec:
      type: cortex_analyst_text_to_sql
      name: acme_analyst
      description: Text-to-SQL over ACME Retail store operations (ACME_SEMANTIC_VIEW).
tool_resources:
  coding_agent:
    permission_policy:
      type: always_ask
  acme_analyst:
    semantic_view: ACME_ASSIST_DEMO.DATA.ACME_SEMANTIC_VIEW
    execution_environment:
      type: warehouse
      warehouse: ACME_ASSIST_WH
$$;

-- 6. Demo role and grants (ACCOUNTADMIN) ---------------------------------
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS ACME_DEMO_ROLE;
GRANT ROLE ACME_DEMO_ROLE TO ROLE SYSADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACME_DEMO_ROLE;
GRANT USAGE ON WAREHOUSE ACME_ASSIST_WH TO ROLE ACME_DEMO_ROLE;
GRANT USAGE ON DATABASE ACME_ASSIST_DEMO TO ROLE ACME_DEMO_ROLE;
GRANT USAGE ON SCHEMA ACME_ASSIST_DEMO.DATA TO ROLE ACME_DEMO_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ACME_ASSIST_DEMO.DATA TO ROLE ACME_DEMO_ROLE;
GRANT SELECT ON SEMANTIC VIEW ACME_ASSIST_DEMO.DATA.ACME_SEMANTIC_VIEW TO ROLE ACME_DEMO_ROLE;
GRANT USAGE ON AGENT ACME_ASSIST_DEMO.DATA.ACME_ASSIST_AGENT TO ROLE ACME_DEMO_ROLE;
GRANT USAGE ON AGENT ACME_ASSIST_DEMO.DATA.ACME_POWER_AGENT TO ROLE ACME_DEMO_ROLE;
-- Grant ACME_DEMO_ROLE to the user whose PAT the app uses, e.g.:
-- GRANT ROLE ACME_DEMO_ROLE TO USER <app_user>;

-- 6b. Caller grants for the App Runtime / SPCS app (CALLERS_RIGHTS=true).
-- A restricted caller's-rights app may only use objects its OWNER role holds
-- caller grants on; without these the app fails with "does not exist or not
-- authorized ... runs with restricted caller's rights". Owner role = SYSADMIN.
GRANT CALLER USAGE ON DATABASE ACME_ASSIST_DEMO TO ROLE SYSADMIN;
GRANT CALLER USAGE ON SCHEMA ACME_ASSIST_DEMO.DATA TO ROLE SYSADMIN;
GRANT CALLER USAGE ON SCHEMA ACME_ASSIST_DEMO.APP TO ROLE SYSADMIN;
GRANT CALLER USAGE ON WAREHOUSE ACME_ASSIST_WH TO ROLE SYSADMIN;
GRANT CALLER USAGE ON AGENT ACME_ASSIST_DEMO.DATA.ACME_ASSIST_AGENT TO ROLE SYSADMIN;
GRANT CALLER USAGE ON AGENT ACME_ASSIST_DEMO.DATA.ACME_POWER_AGENT TO ROLE SYSADMIN;
GRANT CALLER SELECT ON SEMANTIC VIEW ACME_ASSIST_DEMO.DATA.ACME_SEMANTIC_VIEW TO ROLE SYSADMIN;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA ACME_ASSIST_DEMO.DATA TO ROLE SYSADMIN;
-- (history table caller grant lives in history.sql)
USE ROLE SYSADMIN;

