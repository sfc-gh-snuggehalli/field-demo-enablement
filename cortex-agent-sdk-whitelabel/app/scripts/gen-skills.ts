// Generates AGENTS.md, .snowflake/cortex/skills/acme-project/SKILL.md and
// coco-runner/skills.json from shared/skills.ts. Never hand-edit the outputs.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BUILD_ROUTES, PROJECT_FACTS, STUDIO_INTENTS } from "../shared/skills";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const banner = "<!-- GENERATED by `npm run gen:skills` from shared/skills.ts. Do not edit by hand. -->";
const table = ["| Task | Bundled skill |", "|---|---|", ...BUILD_ROUTES.map((r) => `| ${r.task} | ${r.skills.map((s) => `\`${s}\``).join(" + ")} |`)].join("\n");

const agents = `${banner}
# AGENTS.md — ACME Assist

Use only Cortex Code **bundled** skills on this project. No catalog or third-party skills.
**Invoke the matching bundled skill before doing that task.**

${table}

Project facts live in the project skill: \`.snowflake/cortex/skills/acme-project/SKILL.md\`.

Rules:
- Never put Snowflake credentials in the browser bundle; the proxy (\`server/\`) holds them.
- Brand colors only via \`src/brand/brand.config.ts\` and CSS variables.
- Generated files (this file, the project SKILL.md, \`coco-runner/skills.json\`) come from \`shared/skills.ts\`.
`;

const skill = `---
name: acme-project
description: Project facts and task routing for the ACME Assist app (Cortex Agent SDK). Use when working on this repository; routes each task type to a bundled Cortex Code skill.
---
${banner}

# ACME Assist project skill

This skill holds project facts only. For each task, load the bundled skill listed below first.

## Task routing (bundled skills only)
${BUILD_ROUTES.map((r) => `- ${r.task} → ${r.skills.map((s) => `\`${s}\``).join(", ")}`).join("\n")}

## Snowflake objects
- Database: \`${PROJECT_FACTS.database}\` (data schema \`${PROJECT_FACTS.dataSchema}\`, app schema \`${PROJECT_FACTS.appSchema}\`)
- Semantic view: \`${PROJECT_FACTS.semanticView}\`
- Agents: \`${PROJECT_FACTS.agent}\` (Analyst + client-side browser tools), \`${PROJECT_FACTS.powerAgent}\` (code_toolset_all, always_ask)
- Warehouse: \`${PROJECT_FACTS.warehouse}\`
- History table: \`${PROJECT_FACTS.historyTable}\`
- Roles: ${PROJECT_FACTS.roles.map((r) => `\`${r}\``).join(", ")}

## Connection
- Local: PAT via \`SNOWFLAKE_PAT_FILE\` in \`.env\` (never commit). SPCS / App Runtime: \`/snowflake/session/token\`.
- SQL scripts: \`../lab/setup.sql\`, \`../lab/history.sql\`; SPCS: \`snowflake/spcs/\`.

## Brand rules
- Brands: ${PROJECT_FACTS.brands.join(", ")} — defined in \`src/brand/brand.config.ts\`, assets in \`public/brand/<id>/\`.
- No hard-coded brand colors in components; no third-party CDN loads; original SVG assets only.
`;

const runner = {
  generated: "npm run gen:skills (from shared/skills.ts)",
  intents: STUDIO_INTENTS,
  bundledSkills: [...new Set(STUDIO_INTENTS.flatMap((i) => i.skills))],
  policy: "bundled skills only; never auto-install catalog skills",
};

const out: Array<[string, string]> = [
  ["AGENTS.md", agents],
  [".snowflake/cortex/skills/acme-project/SKILL.md", skill],
  ["coco-runner/skills.json", JSON.stringify(runner, null, 2) + "\n"],
];
for (const [rel, content] of out) {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
  console.log(`wrote ${rel}`);
}
